#for loops with list
l = [1,2,3,'sagunm',True,False,34.8,'Ram']
for i in l:
    print(i)
else:
    print("Done!! for List \n")
    
#for loops for Tuple 
t = (1,2,34,'harry','Sagun',True)
for i in t:
    print(i)
else:
    print("Done!!! for Tuple\n")
    
#for String
s = 'SAGUN BHAGAT'
for i in s:
    print(i)
else:
    print('Done!! for String\n')
    
#Range
for i in range(0,20,2): #range(start,end,step-size)  --> End is excluded
    print(i)
    